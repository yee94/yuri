import { expect, open, test } from 'nsh/test';

for (const platform of ['macos', 'windows'] as const) {
  test(`${platform}: production new-session without publisher mounts and submits`, async () => {
    const app = await open('desktop-composer-actions.fixture.tsx', { platform, width: 1280, height: 900 });
    await app.waitFor('id:new-session-composer');
    expect(app.texts()).toContain('registrations:0 retires:0');
    await app.type('id:new-session-composer', 'No publisher must not crash');
    await app.submit('id:new-session-composer');
    await app.waitFor('id:handoff-complete');
    expect(app.texts().join('\n')).not.toContain('unknown-composer-shortcut');
  });

  test(`${platform}: injected submit preserves candidate priority and IME/hidden ownership`, async () => {
    const app = await open('desktop-composer-actions.fixture.tsx', { platform, width: 1280, height: 900 });
    await app.press('id:mode-keyboard');
    await app.waitFor('id:keyboard-input');
    await app.type('id:keyboard-input', '@src');
    await app.press('id:keyboard-submit');
    expect(app.value('id:keyboard-input')).toBe('@src/file.ts ');
    expect(app.texts()).toContain('sends:0');
    await app.clear('id:keyboard-input');
    await app.type('id:keyboard-input', '中文');
    await app.press('id:keyboard-ime-start');
    await app.press('id:keyboard-submit');
    expect(app.texts()).toContain('sends:0');
    await app.press('id:keyboard-ime-end');
    await app.press('id:keyboard-submit');
    expect(app.texts()).toContain('sends:1');
    await app.press('id:keyboard-hide');
    await app.press('id:keyboard-submit');
    expect(app.texts()).toContain('sends:1');
  });
}

test('new-session registered actions mutate local selection only, keep one owner over 50 edits, then hand off', async () => {
  const app = await open('desktop-composer-actions.fixture.tsx', { platform: 'macos', width: 1280, height: 900 });
  await app.waitFor('id:new-session-composer');
  await app.press('id:mode-draft');
  await app.waitFor('text:registrations:1 retires:0');
  await app.press('id:action-open_model_selector');
  await app.waitFor('id:new-session-favorite-model-fixture-gpt-model');
  await app.press('id:new-session-favorite-model-fixture-gpt-model');
  await app.waitFor('id:new-session-selection-search', { state: 'gone' });
  await app.wait(300);
  await app.press('id:action-cycle_thinking_variant');
  await app.waitUntil(() => app.texts().some(text => text.includes('"variant":"low"')));
  await app.press('id:action-cycle-back');
  await app.waitUntil(() => app.texts().some(text => text.includes('"agent":"review"')));
  await app.press('id:action-cycle_agent');
  await app.waitUntil(() => app.texts().some(text => text.includes('"agent":"build"')));
  await app.press('id:action-open_agent_selector');
  await app.waitFor('id:new-session-agent-plan');
  await app.press('id:new-session-agent-plan');
  await app.waitFor('id:new-session-selection-search', { state: 'gone' });
  await app.wait(300);
  await app.press('id:action-audit');
  const stats = () => JSON.parse(app.texts().find(text => text.startsWith('{"requests":'))!);
  const before = stats();
  expect(before.creates).toBe(0); expect(before.writes.length).toBe(0);
  await app.press('id:action-focus_input');
  for (let index = 0; index < 50; index++) await app.type('id:new-session-composer', 'x');
  await app.press('id:action-audit');
  expect(stats().requests).toBe(before.requests);
  expect(stats().catalogReads).toBe(before.catalogReads);
  expect(app.texts()).toContain('registrations:1 retires:0');
  await app.press('id:action-clear_input');
  expect(app.value('id:new-session-composer')).toBe('');
  await app.type('id:new-session-composer', '/mo');
  await app.waitFor('id:command-model');
  await app.keyboard.press('mod+enter');
  await app.waitFor('id:new-session-selection-search');
  expect(app.shows('id:handoff-complete')).toBe(false);
  await app.keyboard.press('escape');
  await app.waitFor('id:new-session-selection-search', { state: 'gone' });
  await app.wait(300);
  await app.press('id:action-focus_input');
  await app.type('id:new-session-composer', 'Captured native shortcut input');
  await app.press('id:action-submit_message');
  await app.waitFor('id:handoff-complete');
});

test('Chat selection actions use captured Host scope and both cycle directions; pending and late owners cannot write', async () => {
  const app = await open('desktop-composer-actions.fixture.tsx', { platform: 'windows', width: 1280, height: 900 });
  await app.press('id:mode-chat');
  await app.waitFor('label:build');
  await app.press('id:action-cycle-back');
  await app.waitFor('label:review');
  await app.press('id:action-cycle_agent');
  await app.waitFor('label:build');
  await app.press('id:action-cycle_thinking_variant');
  await app.waitUntil(() => app.texts().some(text => text.includes('"variant":"low"')));
  await app.press('id:action-cycle_thinking_variant');
  await app.waitUntil(() => app.texts().some(text => text.includes('"variant":"high"')));
  await app.press('id:action-defer');
  await app.press('id:action-cycle_agent');
  await app.press('id:action-cycle_agent');
  await app.press('id:action-audit');
  const stats = () => JSON.parse(app.texts().find(text => text.startsWith('{"requests":'))!);
  expect(stats().writes.length).toBe(5);
  await app.press('id:action-hide');
  await app.press('id:action-release');
  await app.wait(150);
  expect(app.shows('label:plan')).toBe(false);
  await app.press('id:action-cycle_agent');
  await app.press('id:action-audit');
  expect(stats().writes.length).toBe(5);
  await app.press('id:action-show');
  await app.waitFor('label:plan');
  await app.press('id:action-defer');
  await app.press('id:action-cycle_agent');
  await app.press('id:action-audit');
  const readsBeforeUnmount = stats().reads;
  expect(stats().writes.length).toBe(6);
  await app.press('id:mode-draft');
  await app.waitFor('text:registrations:2 retires:1');
  await app.press('id:action-release');
  await app.wait(150);
  await app.press('id:action-retired');
  await app.press('id:action-audit');
  expect(stats().writes.length).toBe(6);
  expect(stats().reads).toBe(readsBeforeUnmount);
  expect(app.texts().some(text => text.startsWith('{"id":"selection-session"'))).toBe(false);
  await app.press('id:action-focus_input');
  await app.type('id:new-session-composer', 'The replacement owner is still editable');
  expect(app.value('id:new-session-composer')).toBe('The replacement owner is still editable');
  expect(app.texts()).toContain('registrations:2 retires:1');
});

test('Assistant selection shortcuts use revision-checked PATCH rather than session endpoints', async () => {
  const app = await open('desktop-composer-actions.fixture.tsx', { platform: 'macos', width: 1280, height: 900 });
  await app.press('id:mode-assistant');
  await app.waitFor('label:build');
  await app.press('id:action-cycle-back');
  await app.waitFor('label:review');
  await app.press('id:action-cycle_thinking_variant');
  await app.waitUntil(() => app.texts().some(text => text.includes('"variant":"low"')));
  await app.press('id:action-open_agent_selector');
  await app.waitFor('text:assistant edit requested');
  await app.press('id:action-audit');
  const stats = JSON.parse(app.texts().find(text => text.startsWith('{"requests":'))!);
  expect(stats.creates).toBe(0); expect(stats.writes.length).toBe(2);
  expect(stats.writes[0].path).toBe('/api/yuri/assistants/selection-bot');
  expect(stats.writes[0].body.expectedRevision).toBe(1);
  expect(stats.writes[1].body.expectedRevision).toBe(2);
  expect(stats.writes[1].body.variant).toBe('low');
});
