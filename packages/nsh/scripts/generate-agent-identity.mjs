// Run with Bun. DiceBear is a build-time dependency, never a QuickJS import.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { generatedAvatarDataUri } from '../../ui/src/lib/generatedAvatar.ts';

const output = path.join(path.dirname(fileURLToPath(import.meta.url)), '../agent-avatar-templates.ts');
const marker = '__YURI_AGENT_BACKGROUND__', sentinel = '#1a2b3c';
const templates = {};
for (const name of ['build', 'plan', 'explore', 'general']) {
  const uri = generatedAvatarDataUri('agent', name, false, { background: sentinel });
  const comma = uri.indexOf(',');
  const svg = uri.slice(0, comma).includes(';base64') ? Buffer.from(uri.slice(comma + 1), 'base64').toString('utf8') : decodeURIComponent(uri.slice(comma + 1));
  if (svg.split(sentinel).length !== 2 || !svg.includes('<metadata') || !svg.includes('Pablo Stanley')) throw new Error('Agent template geometry/color/attribution contract changed');
  templates[name] = svg.replace(sentinel, marker);
}
const source = '// Generated by scripts/generate-agent-identity.mjs; do not edit. Original DiceBear artwork attribution remains embedded.\n'
  + `export const nativeAgentPlateMarker = ${JSON.stringify(marker)};\n`
  + `export const nativeAgentAvatarTemplates = ${JSON.stringify(templates, null, 2)} as const;\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== source) throw new Error('Agent templates are stale; regenerate with Bun');
} else writeFileSync(output, source);
