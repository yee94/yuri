// Run with Bun. Adapt the pinned upstream renderer at build time, never globals.
import { createHash } from 'node:crypto';
import { createRequire } from 'node:module';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const workspaceRoot = path.resolve(packageRoot, '../..');
const require = createRequire(path.join(workspaceRoot, 'packages/ui/package.json'));
const coreRoot = path.resolve(path.dirname(require.resolve('@dicebear/core')), '..');
const styleFile = require.resolve('@dicebear/styles/bottts-neutral.json');
const styleRoot = path.resolve(path.dirname(styleFile), '..');
const core = JSON.parse(await readFile(path.join(coreRoot, 'package.json'), 'utf8'));
const styles = JSON.parse(await readFile(path.join(styleRoot, 'package.json'), 'utf8'));
if (core.version !== '10.7.0' || styles.version !== '10.6.0') throw new Error('Review the native DiceBear adapter before updating pinned versions');
const expectedClones = { 'Avatar.js': 1, 'Options.js': 1, 'OptionsDescriptor.js': 1, 'Style.js': 3 };
const runtimeClones = { 'Avatar.js': 1, 'Options.js': 1, 'Style.js': 3 };
for (const [name, count] of Object.entries(expectedClones)) {
  const source = await readFile(path.join(coreRoot, 'lib', name), 'utf8');
  if ((source.match(/\bstructuredClone\(/g)?.length ?? 0) !== count) throw new Error(`Pinned DiceBear clone sites changed: ${name}`);
}
const adapted = new Map(), inputs = new Map();
const relative = file => path.relative(workspaceRoot, file).split(path.sep).join('/');
const digest = source => createHash('sha256').update(source).digest('hex');
const clone = path.join(packageRoot, 'agent-avatar-clone.ts');
const entry = path.join(workspaceRoot, 'packages/ui/src/lib/agentAvatarDataUri.ts');
const build = await Bun.build({
  entrypoints: [entry], root: workspaceRoot, target: 'browser', format: 'esm',
  minify: { whitespace: true, syntax: true, identifiers: false },
  plugins: [{
    name: 'native-agent-artwork-local-clone',
    setup(builder) {
      builder.onLoad({ filter: /\.(?:js|ts|json)$/ }, async ({ path: file }) => {
        const source = await readFile(file, 'utf8');
        inputs.set(relative(file), digest(source));
        if (!file.startsWith(path.join(coreRoot, 'lib') + path.sep)) return;
        const count = source.match(/\bstructuredClone\(/g)?.length ?? 0;
        const name = path.relative(path.join(coreRoot, 'lib'), file);
        if (count !== (expectedClones[name] ?? 0)) throw new Error(`DiceBear clone boundary changed: ${name}`);
        if (!count) return;
        adapted.set(name, count);
        // Lexical binding only. Upstream validators and rendering code are intact.
        return { loader: 'js', contents: `import { cloneAgentArtworkData as structuredClone } from ${JSON.stringify(clone)};\n${source}` };
      });
    },
  }],
});
if (!build.success) throw new AggregateError(build.logs, 'Native agent artwork bundling failed');
if (JSON.stringify(Object.fromEntries([...adapted].sort())) !== JSON.stringify(runtimeClones)) throw new Error(`Native renderer clone sites changed: ${JSON.stringify(Object.fromEntries(adapted))}`);
if (build.outputs.length !== 1) throw new Error('Native agent artwork must be a standalone module');
const bundled = await build.outputs[0].text();
const imports = new Bun.Transpiler({ loader: 'js' }).scanImports(bundled);
if (imports.length || bundled.includes(workspaceRoot) || /\beval\s*\(|\bnew Function\b|globalThis\.structuredClone/.test(bundled)) throw new Error('Native artwork contains an external dependency, executable adapter or global shim');
const license = await readFile(path.join(coreRoot, 'LICENSE'), 'utf8');
const source = `// Generated by scripts/generate-agent-artwork.mjs; do not edit.\n/*\n${license.replaceAll('*/', '* /')}\n*/\n${bundled}\n`;
const declaration = '// Generated by scripts/generate-agent-artwork.mjs; do not edit.\n'
  + "import type { AvatarColorSet } from '../ui/src/lib/agentAvatarPalette';\n"
  + 'export declare function agentAvatarDataUri(seed: string | undefined, colors?: AvatarColorSet): string;\n';
const metadata = JSON.stringify({
  schemaVersion: 1, coreVersion: core.version, stylesVersion: styles.version,
  entry: relative(entry), clone: relative(clone), generatorSha256: digest(await readFile(fileURLToPath(import.meta.url))),
  auditedCloneSites: expectedClones, adaptedCloneSites: runtimeClones, externalImports: imports,
  inputs: Object.fromEntries([...inputs].sort()), outputSha256: digest(source), declarationSha256: digest(declaration),
}, null, 2) + '\n';
const outputs = [
  ['agent-avatar-runtime.generated.js', source],
  ['agent-avatar-runtime.generated.d.ts', declaration],
  ['agent-avatar-runtime.generated.meta.json', metadata],
];
for (const [name, contents] of outputs) {
  const file = path.join(packageRoot, name);
  if (process.argv.includes('--check')) {
    if (await readFile(file, 'utf8') !== contents) throw new Error(`Native agent artwork is stale: ${name}`);
  } else await writeFile(file, contents);
}
console.log(`Native agent artwork: ${inputs.size} source modules, ${adapted.size} clone-adapted modules, no external imports`);
