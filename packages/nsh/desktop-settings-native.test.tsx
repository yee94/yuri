import { expect, open, test } from 'nsh/test';

test('desktop split geometry, native resize limits, target navigation, real i18n and tokens', async () => {
  const app = await open('./desktop-settings-fixture.tsx', { platform: 'macos', width: 1200, height: 800 });
  await app.waitFor('id:desktop-settings-window');
  await app.waitFor('id:desktop-settings-page:appearance');
  expect(app.count('role:adjustable')).toBe(1);
  const size = () => app.texts().find(text => text.startsWith('slot='))!.slice(5).split('x').map(Number);
  const initial = size();
  expect(initial[0] > 800 && initial[0] < 900).toBe(true);
  await app.drag('label:Resize left panel', { x: -400, y: 0 });
  expect(Math.abs(size()[0] - initial[0] - 48) < 2).toBe(true);
  await app.drag('label:Resize left panel', { x: 500, y: 0 });
  expect(Math.abs(size()[0] - initial[0] + 56) < 2).toBe(true);
  await app.type('id:desktop-settings-search', 'messageStreamTransport');
  await app.waitFor('id:desktop-settings-field:chat.message-transport');
  await app.keyboard.press('down'); await app.keyboard.press('up'); await app.keyboard.press('enter');
  await app.waitFor('text:{"page":"chat","target":"chat.message-transport","directory":"/fixture/worktree"}');
  await app.press('id:fixture-language');
  await app.waitFor('text:Налаштування');
  expect(app.texts().some(text => text.startsWith('Delete this provider'))).toBe(false);
  const light = app.spanStyle('text:' + app.texts().find(text => text.startsWith('Видаляє конфігурацію'))!).color;
  await app.setColorScheme('dark');
  expect(app.spanStyle('text:' + app.texts().find(text => text.startsWith('Видаляє конфігурацію'))!).color === light).toBe(false);
  await app.setViewport(2400, 1600);
  expect(Math.abs(size()[0] - 918) < 2).toBe(true);
  expect(Math.abs(size()[1] - 849) < 2).toBe(true);
  await app.setViewport(720, 500);
  expect(size()[0] > 300 && size()[0] < 500).toBe(true);
  expect(size()[1] > 300 && size()[1] < 425).toBe(true);
  expect(app.requests().length).toBe(0);
});

test('only the owner closes: pending/dirty guards, backdrop, Escape and native nested pickers', async () => {
  const app = await open('./desktop-settings-fixture.tsx', { platform: 'macos', width: 1200, height: 900 });
  await app.waitFor('id:desktop-settings-close');
  await app.press('id:desktop-settings-close');
  await app.waitFor('text:closes=1, navigations=0, confirmations=0');
  expect(app.shows('id:desktop-settings-window')).toBe(true);
  await app.press('id:fixture-pending');
  expect(app.enabled('id:desktop-settings-close')).toBe(false);
  await app.keyboard.press('escape');
  expect(app.texts()).toContain('closes=1, navigations=0, confirmations=0');
  await app.press('id:fixture-pending'); await app.press('id:fixture-dirty');
  await app.press('id:desktop-settings-close');
  await app.waitFor('text:closes=1, navigations=0, confirmations=1');
  expect(app.shows('id:desktop-settings-window')).toBe(true);
  await app.press('id:desktop-settings-page:chat');
  await app.waitFor('text:closes=1, navigations=0, confirmations=2');
  await app.press('id:fixture-dirty');
  await app.press('id:fixture-picker'); await app.waitFor('text:Nested choice one');
  await app.keyboard.press('escape');
  await app.waitFor('text:Nested choice one', { state: 'gone' });
  expect(app.texts()).toContain('closes=1, navigations=0, confirmations=2');
  await app.press('id:fixture-modal'); await app.waitFor('id:fixture-modal-content');
  await app.keyboard.press('escape'); await app.waitFor('id:fixture-modal-content', { state: 'gone' });
  expect(app.texts()).toContain('closes=1, navigations=0, confirmations=2');
  await app.press('id:desktop-settings-backdrop');
  await app.waitFor('text:closes=2, navigations=0, confirmations=2');
  expect(app.shows('id:desktop-settings-window')).toBe(true);
  await app.press('id:fixture-owner-closes');
  await app.keyboard.press('escape'); await app.waitFor('id:desktop-settings-window', { state: 'gone' });
  expect(app.texts()).toContain('owner-closes=3');
  await app.press('id:fixture-reopen'); await app.waitFor('id:desktop-settings-window');
});

test('active and lifecycle gates stop navigation and propagate to the actual page slot', async () => {
  const app = await open('./desktop-settings-fixture.tsx', { platform: 'macos', width: 1200, height: 900 });
  await app.waitFor('text:active=true');
  await app.setLifecycle('background');
  expect(app.texts()).toContain('owner-closes=0');
  await app.setLifecycle('active'); await app.waitFor('text:active=true');
  await app.press('id:fixture-active-toggle'); await app.waitFor('text:active=false');
  expect(app.enabled('id:desktop-settings-close')).toBe(false);
  expect(app.enabled('id:desktop-settings-search')).toBe(false);
  await app.press('id:fixture-active-toggle'); await app.waitFor('text:active=true');
  await app.type('id:desktop-settings-search', 'not-a-settings-result'); await app.waitFor('id:desktop-settings-empty');
  await app.keyboard.press('enter');
  expect(app.texts()).toContain('closes=0, navigations=0, confirmations=0');
});
