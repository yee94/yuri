import { spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, test } from 'vitest';

const directory = path.dirname(fileURLToPath(import.meta.url));
function run(steps: string[], desktop = false, trace = false) {
  const temporary = mkdtempSync(path.join(process.env.TMPDIR || tmpdir(), 'nsh-desktop-panel-'));
  try {
    writeFileSync(path.join(temporary, 'nsh.json'), JSON.stringify({ name: 'Desktop panel test', id: 'example.yuri.desktop-panel', version: '0.1.0', build: 1, theme: path.join(directory, 'theme.json'), capabilities: { clipboard: true, host: ['runtime.request', 'resources.read', 'resources.cancel', 'resources.close', 'resources.release', 'resources.web.close'] } }));
    writeFileSync(path.join(temporary, 'App.tsx'), `import ${JSON.stringify(path.join(directory, 'desktop-panel-fixture.tsx'))};\n`);
    const script = [
        'const state = () => JSON.parse(app.texts().find(text => text.startsWith("panel-state:")).slice(12));',
        'const stats = () => JSON.parse(app.texts().find(text => text.startsWith("panel-stats:")).slice(12));',
        'await app.waitFor("id:native-desktop-panel");',
        ...steps,
      ].join('\n');
    if (desktop) writeFileSync(path.join(temporary, 'Desktop.test.ts'), `import { test, open, expect } from 'nsh/test'; test('desktop panel', async () => { const app = await open('App.tsx', { platform: 'macos', width: 1200, height: 1000 }); ${script} }, 60000);`);
    const result = spawnSync(process.env.NSH_BIN || 'nsh', ['test', desktop ? 'Desktop.test.ts' : 'App.tsx', '--web-host', path.join(directory, 'desktop-panel-fixture-host.js'), ...(trace ? ['--trace'] : [])], {
      cwd: temporary, encoding: 'utf8', timeout: 70_000, maxBuffer: trace ? 16 * 1024 * 1024 : 1024 * 1024,
      ...(desktop ? {} : { input: script }),
    });
    expect(result.error, result.stdout + result.stderr).toBeUndefined();
    expect(result.status, result.stdout + result.stderr).toBe(0);
    return result.stdout + result.stderr;
  } finally { rmSync(temporary, { recursive: true, force: true }); }
}

