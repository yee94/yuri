import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { expect, it } from 'vitest';

it('keeps the experiment opt-in, batches the hidden-content handoff, and uses the measured footer owner without scroll writes', () => {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
  const fixture = readFileSync(path.join(root, 'history-terminal-fixture.tsx'), 'utf8');
  const owner = readFileSync(path.join(root, 'history-footer.ts'), 'utf8');
  expect(fixture).toContain('const footerExperiment = signal(false)');
  expect(fixture).toContain('value => batch(() => {');
  expect(fixture.indexOf('updateFooter(value, snapshot().pending')).toBeLessThan(fixture.indexOf('snapshot.set(value)'));
  expect(fixture).toContain('style={{ minHeight: footerState().minHeight || undefined }}');
  expect(fixture).toContain('source = natural.captureSource(footerScope, key)');
  expect(fixture).toContain('const height = event.bounds.size.height, admitted = source.onLayout(event)');
  expect(fixture).toContain('testID="terminal-footer-natural"');
  expect(fixture).toContain('const admitted = await natural.measure()');
  expect(fixture).toContain("source: 'ref.measure.bounds.size.height'");
  expect(fixture).toContain('footerPublishedOffsetY: published.offsetY');
  expect(fixture).toContain('footerHold: footer.snapshot()');
  expect(fixture).toContain('if (sawActive) footerNeedsActiveRead = true');
  expect(fixture).toContain('footerNeedsActiveRead || footer.snapshot().measuredHeight <= 0');
  expect(fixture).toContain('footer.onScroll(event.offset.y); historyScroll.onScroll(event)');
  expect(fixture).toContain('generation !== gestureGeneration');
  expect(fixture).toContain("await measure('before-footer-release')");
  const sync = fixture.slice(fixture.indexOf("if (releaseMode() === 'sync')"), fixture.indexOf('const before = footer.snapshot(), generation = gestureGeneration'));
  expect(sync).toContain('releaseFooterSynchronously');
  expect(sync).toContain('existing-native-display-link-ring-only');
  expect(sync).not.toContain('await ');
  const native = readFileSync(path.join(root, 'tests/history-terminal/TerminalObserver.swift'), 'utf8');
  expect(native).toContain('!continuous && ProcessInfo.processInfo.systemUptime >= stopAt');
  expect(native).toContain('self.cachedPre(payload)');
  expect(native).toContain('postWindow.takeReady(atNativeSampleMs: t)');
  expect(native).toContain('post-window-snapshot');
  expect(native).toContain('capture["persistedSnapshotRevision"] = try await self.flushContinuous()');
  const syncNative = native.slice(native.indexOf('if phase == "footer-sync-before-release"'), native.indexOf('self.events.append(["sequence"'));
  expect(syncNative).not.toContain('self.capture(');
  expect(syncNative).not.toContain('flush(');
  expect(owner).not.toMatch(/setTimeout|setInterval|scrollTo|contentInset|contentOffset|maintainVisibleContentPosition/);
  expect(fixture).not.toMatch(/scrollTo|contentInset|contentOffset|maintainVisibleContentPosition/);
});
